const norm = (s) => String(s || '').toLowerCase().replace(/\s+/g, '');
// 問句像在「查數字」：導到「用問的」
const DATA_Q = /(多少|幾筆|幾個|賣最好|最好賣|營收|業績|排名|比較|趨勢|上個月|這個月|今年|去年|上週|本週)/;

export function matchKB(q, allowed = () => true) {
  const n = norm(q);
  if (!n) return [];
  return KB.filter(allowed).map(e => {
    let s = 0;
    for (const k of e.k) { const kk = norm(k); if (kk && n.includes(kk)) s += kk.length + 1; }
    if (norm(e.t).includes(n)) s += 3;
    return [s, e];
  }).filter(([s]) => s > 0).sort((a, b) => b[0] - a[0]).map(([s, e]) => ({ ...e, score: s }));
}
export const looksLikeDataQuestion = (q) => DATA_Q.test(q);
